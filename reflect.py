"""Reflection: the part where the brain looks at itself.

    uv run python reflect.py          # generate notes/_reflection.md
    uv run python reflect.py --show   # just print what's there

Two rules make this safe:

1. It writes to ONE file, `notes/_reflection.md`, which is excluded from
   recall. Reflections never contaminate the facts the model retrieves.
2. Every line is labelled as generated. Patterns are guesses about you, not
   memories. You read them, you decide what's true, and you can delete the
   whole file without losing anything.

Why bother? Because it's the first place you'll see a model confabulate
confidently about *you* — the exact failure mode that makes personal AI
systems dangerous if you can't tell memory from inference.
"""

from __future__ import annotations

import datetime as dt
import sys

import memory
from llm import chat

PROMPT = """Here are notes I wrote about myself.

Find patterns. Be specific and quote the notes that support each claim.

Output Markdown in exactly these three sections:

## Themes
Recurring subjects, 2-4 bullets.

## Tensions
Things that pull against each other, or statements that conflict. 1-3 bullets.
If you find none, say "None found."

## Open questions
Questions my notes raise but don't answer, 2-3 bullets.
Phrase them as questions to me, not conclusions about me.

Rules:
- Use ONLY what is in the notes. If you are guessing, write "(guess)".
- No advice, no encouragement, no lists of generic productivity tips.
- Maximum 120 words total. Dense beats long.

NOTES
-----
{notes}
"""

HEADER = """<!-- generated by reflect.py on {stamp} from {count} notes -->
<!-- This is inference, not memory. It is excluded from recall on purpose. -->

# Reflection

> Generated, not verified. Anything here can be wrong; you are the source of truth.

"""


def notes_block(budget: int = 12_000) -> str:
    parts = []
    for path in memory.note_paths():  # already excludes _digest and _reflection
        body = path.read_text(encoding="utf-8", errors="ignore")
        parts.append(f"- {body.split('---', 2)[-1].strip()}")
    text = "\n".join(parts)
    return text[-budget:]


def main() -> None:
    out = memory.NOTES / "_reflection.md"

    if "--show" in sys.argv:
        print(out.read_text() if out.exists() else "(no reflection yet)")
        return

    count = len(memory.note_paths())
    if count < 4:
        print(f"Only {count} notes. Write a few more first — patterns need material.")
        return

    print(f"reflecting on {count} notes…")
    body = chat(
        [{"role": "user", "content": PROMPT.format(notes=notes_block())}],
        temperature=0.4,
    ).content or "(the model returned nothing)"

    out.write_text(
        HEADER.format(
            stamp=dt.datetime.now().isoformat(timespec="seconds"), count=count
        )
        + body.strip()
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out}\n\n{body.strip()}")


if __name__ == "__main__":
    main()
